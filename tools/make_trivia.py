#!/usr/bin/env python3
"""Build Table Talk's question data from tools/trivia.txt.

Writes table-talk/questions.js (window.TT_QUESTIONS). Answer order is shuffled once here,
with a fixed seed per question, so any recorded audio always matches what's on screen.
  python3 tools/make_trivia.py           # questions only
  python3 tools/make_trivia.py --audio   # also record read-aloud clips (macOS `say`); skips existing clips
"""
import json, os, random, re, subprocess, sys, tempfile
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'trivia.txt')
OUT = os.path.join(HERE, '..', 'table-talk', 'questions.js')
AUDIO = os.path.join(HERE, '..', 'table-talk', 'audio')
VOICE, RATE = 'Samantha', '165'
PHRASES = ["That's right!", 'You got it!', 'Brilliant!', 'Super!', 'Yes!', 'Not quite!', 'The answer is',
           'Fun fact!', 'Is it', 'or', "It's your turn!", 'What a team!', 'Superstars!', 'Great playing!']
CATS = ['india', 'science', 'animals', 'space', 'geo', 'history', 'tech', 'food', 'body', 'words']

def load():
    qs, counts = [], {}
    for n, line in enumerate(open(SRC, encoding='utf-8'), 1):
        line = line.strip()
        if not line or line.startswith('#'): continue
        parts = [p.strip() for p in line.split('|')]
        assert len(parts) == 5, f'line {n}: expected 5 fields'
        cat, level, q, answers, fact = parts
        assert cat in CATS, f'line {n}: unknown category {cat}'
        assert level in ('easy', 'tricky'), f'line {n}: unknown level {level}'
        opts = [a.strip() for a in answers.split(';')]
        assert len(opts) == 3 and len(set(opts)) == 3, f'line {n}: need 3 different answers'
        counts[cat] = counts.get(cat, 0) + 1
        qid = f'{cat}-{counts[cat]:02d}'
        rng = random.Random(qid)
        order = [0, 1, 2]; rng.shuffle(order)
        say = None
        if '>>' in q: q, say = [x.strip() for x in q.split('>>', 1)]  # show one thing, say another
        qs.append({'id': qid, 'cat': cat, 'level': level, 'q': q, **({'say': say} if say else {}),
                   'a': [opts[i] for i in order], 'c': order.index(0), 'fact': fact})
    return qs

def slug(t): return re.sub(r'[^a-z0-9]+', '-', t.lower()).strip('-')[:60]

def record(job):
    key, text = job
    out = os.path.join(AUDIO, key + '.m4a')
    if os.path.exists(out): return
    tmp = tempfile.mktemp(suffix='.aiff')
    for _ in range(3):  # `say` occasionally hangs; retry with a timeout
        try:
            subprocess.run(['say', '-v', VOICE, '-r', RATE, '-o', tmp, text], check=True, timeout=30); break
        except subprocess.TimeoutExpired:
            pass
    subprocess.run(['afconvert', '-f', 'm4af', '-d', 'aac', '-b', '48000', tmp, out], check=True, timeout=30)
    os.unlink(tmp)

def add_audio(qs):
    jobs, opts = {}, {}
    for q in qs:
        q['qa'] = 'q-' + q['id']; jobs[q['qa']] = q.get('say', q['q'])
        q['fa'] = 'f-' + q['id']; jobs[q['fa']] = q['fact']
        q['oa'] = []
        for a in q['a']:
            k = 'o-' + slug(a); jobs[k] = a; q['oa'].append(k)
    phrases = {p: 'p-' + slug(p) for p in PHRASES}
    for p, k in phrases.items(): jobs[k] = p
    os.makedirs(AUDIO, exist_ok=True)
    todo = [(k, t) for k, t in jobs.items() if not os.path.exists(os.path.join(AUDIO, k + '.m4a'))]
    print(f'{len(jobs)} clips, {len(todo)} to record', flush=True)
    with ThreadPoolExecutor(6) as pool:
        for n, _ in enumerate(pool.map(record, todo), 1):
            if n % 100 == 0: print(n, 'recorded', flush=True)
    return phrases

if __name__ == '__main__':
    qs = load()
    phrases = add_audio(qs) if '--audio' in sys.argv else None
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/make_trivia.py from tools/trivia.txt. Do not edit by hand.\n')
        f.write('window.TT_QUESTIONS = ' + json.dumps(qs, ensure_ascii=False, indent=0) + ';\n')
        if phrases: f.write('window.TT_PHRASES = ' + json.dumps(phrases) + ';\n')
    by = {}
    for q in qs: by.setdefault(q['cat'], []).append(q['level'])
    print(len(qs), 'questions:', ', '.join(f"{c} {len(v)} ({v.count('easy')} easy)" for c, v in by.items()))
