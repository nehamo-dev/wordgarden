#!/usr/bin/env python3
"""Record Word Garden's audio clips with the macOS `say` voice (Samantha).

Writes word-garden/audio/<key>.m4a and word-garden/audio/manifest.js.
Re-run after adding words to WORDS; existing clips are skipped.
  python3 tools/make_audio.py
"""
import json, os, re, subprocess, tempfile

ROOT = os.path.join(os.path.dirname(__file__), '..', 'word-garden', 'audio')
VOICE, RATE = 'Samantha', '150'

# Dolch sight words (pre-primer → 3rd grade) plus Word Garden's filler words.
WORDS = """
a and away big blue can come down find for funny go help here i in is it jump little look make me my not one play red run said see the three to two up we where yellow you
all am are at ate be black brown but came did do eat four get good have he into like must new no now on our out please pretty ran ride saw say she so soon that there they this too under want was well went what white who will with yes
after again an any as ask by could every fly from give going had has her him his how just know let live may of old once open over put round some stop take thank them then think walk were when
always around because been before best both buy call cold does don't fast first five found gave goes green its made many off or pull read right sing sit sleep tell their these those upon us use very wash which why wish work would write your
about better bring carry clean cut done draw drink eight fall far full got grow hold hot hurt if keep kind laugh light long much myself never only own pick seven shall show six small start ten today together try warm
""".split()

# How to pronounce things the voice gets wrong on their own.
SAY_WORD = {'a': 'uh', 'i': 'I', 'read': 'reed', 'live': 'liv', 'wind': 'wind'}
LETTERS = {'a':'ay','b':'bee','c':'see','d':'dee','e':'ee','f':'eff','g':'jee','h':'aitch','i':'eye','j':'jay','k':'kay','l':'ell','m':'em',
           'n':'en','o':'oh','p':'pee','q':'cue','r':'are','s':'ess','t':'tee','u':'you','v':'vee','w':'double you','x':'ex','y':'why','z':'zee'}
PHRASES = ['You got it!', 'Great job!', 'Super reading!', 'Wow!', 'Yes!', 'Amazing!', 'Nice one!',
           'Hmm, try again!', 'Almost! Try again.', 'Oops! One more try.', 'Keep going!', 'Hooray! Great playing!']

def slug(t): return re.sub(r'[^a-z0-9]+', '-', t.lower()).strip('-')
def key_word(w): return 'w-' + slug(w.replace("'", ''))

def record(key, text):
    out = os.path.join(ROOT, key + '.m4a')
    if os.path.exists(out): return
    tmp = tempfile.mktemp(suffix='.aiff')
    for attempt in range(3):  # `say` occasionally hangs; retry with a timeout
        try:
            subprocess.run(['say', '-v', VOICE, '-r', RATE, '-o', tmp, text], check=True, timeout=20)
            break
        except subprocess.TimeoutExpired:
            print('retrying', key)
    subprocess.run(['afconvert', '-f', 'm4af', '-d', 'aac', '-b', '48000', tmp, out], check=True, timeout=30)
    os.unlink(tmp)

os.makedirs(ROOT, exist_ok=True)
manifest = {'words': {}, 'letters': {}, 'phrases': {}}
for w in dict.fromkeys(WORDS):
    k = key_word(w); record(k, SAY_WORD.get(w, w)); manifest['words'][w] = k
for c, t in LETTERS.items():
    k = 'l-' + c; record(k, t); manifest['letters'][c] = k
for p in PHRASES:
    k = 'p-' + slug(p); record(k, p); manifest['phrases'][p] = k
with open(os.path.join(ROOT, 'manifest.js'), 'w') as f:
    f.write('// Generated by tools/make_audio.py. Do not edit by hand.\nwindow.WG_AUDIO = ' + json.dumps(manifest) + ';\n')
print(len(manifest['words']), 'words,', len(manifest['letters']), 'letters,', len(manifest['phrases']), 'phrases')
